****
** factor.asm -- factor 32 bit numbers
****
    AORG >0000
    DATA WPA    ; WP
    DATA START  ; PC

    AORG >1000  ; workspaces
WPA BSS >20
WPB BSS >20

    AORG >1800
START
    LI R00, >1700        ; output pointer
    MOV @>17FC, R03      ; N high
    MOV @>17FE, R04      ; N low

    CI R03, >0000
    JNE FACTOR_INIT
    CI R04, >0000
    JNE FACTOR_INIT
    LI R01, >0000
    MOV R01, *R00+
    MOV R01, *R00+
    IDLE

FACTOR_INIT
    LI R05, >0002        ; divisor

FACTOR_LOOP
    CI R03, >0000
    JNE CHECK_DIV
    CI R04, >0001
    JEQ DONE

CHECK_DIV
    MOV R05, R09
    MPY R05, R09
    C R03, R09
    JEQ CMP_LOW
    JH REMAINING_32
    JMP TRY_DIV

CMP_LOW
    C R04, R10
    JH REMAINING_32
    JMP TRY_DIV

TRY_DIV
    MOV R03, R11
    MOV R04, R12
    LI R06, >0000        ; remainder
    LI R07, >0000        ; quotient high
    LI R08, >0000        ; quotient low
    LI R02, >0020        ; 32 bits

DIV32_LOOP
    LI R09, >0000
    SLA R04, 1
    JOC DIV32_LOW_CARRY
    JMP DIV32_LOW_DONE
DIV32_LOW_CARRY
    LI R09, >0001
DIV32_LOW_DONE
    LI R10, >0000
    SLA R03, 1
    JOC DIV32_HIGH_CARRY
    JMP DIV32_HIGH_DONE
DIV32_HIGH_CARRY
    LI R10, >0001
DIV32_HIGH_DONE
    CI R09, >0000
    JEQ DIV32_SKIP_HIGH_LSB
    ORI R03, >0001
DIV32_SKIP_HIGH_LSB
    SLA R06, 1
    CI R10, >0000
    JEQ DIV32_SKIP_REM_LSB
    ORI R06, >0001
DIV32_SKIP_REM_LSB
    LI R09, >0000
    SLA R08, 1
    JOC DIV32_QLOW_CARRY
    JMP DIV32_QLOW_DONE
DIV32_QLOW_CARRY
    LI R09, >0001
DIV32_QLOW_DONE
    SLA R07, 1
    CI R09, >0000
    JEQ DIV32_QSKIP_HIGH_LSB
    ORI R07, >0001
DIV32_QSKIP_HIGH_LSB
    C R05, R06
    JHE DIV32_REM_GE
    JMP DIV32_REM_LT
DIV32_REM_GE
    S R05, R06
    ORI R08, >0001
DIV32_REM_LT
    DEC R02
    JNE DIV32_LOOP

    CI R06, >0000
    JEQ FOUND_FACTOR

    MOV R11, R03
    MOV R12, R04
    CI R05, >0002
    JEQ SET_DIV3
    AI R05, >0002
    JMP FACTOR_LOOP

SET_DIV3
    LI R05, >0003
    JMP FACTOR_LOOP

FOUND_FACTOR
    MOV R07, R03
    MOV R08, R04
    LI R01, >0000
    MOV R01, *R00+
    MOV R05, *R00+
    JMP FACTOR_LOOP

REMAINING_32
    MOV R03, *R00+
    MOV R04, *R00+
    JMP DONE

DONE
    LI R01, >0000
    MOV R01, *R00+
    MOV R01, *R00+
    IDLE
